"""Generate Improved Inventory's stat/effect filter tables from the game data.

Reads item ability definitions from the installed game's resources.gpak and
writes mods/improved-inventory/src/native/inventory_trait_tables.h. Item
definitions themselves are scanned at runtime from the effective loaded data;
only ability effects come from this build-time table. Never writes game files.
"""
import argparse
from pathlib import Path
import re
import sys

from probe_inventory import Gpak

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'mods/improved-inventory/src/native/inventory_trait_tables.h'
ABILITY_FILES = ('data/abilities/item_abilities.gon', 'data/abilities/consumable_item_abilities.gon')

# Item fields in game order of the wiki's main stats, with their "Up" passive.
STATS = [('str', 'StrengthUp', 'STR'), ('dex', 'DexterityUp', 'DEX'), ('con', 'ConstitutionUp', 'CON'),
         ('int', 'IntelligenceUp', 'INT'), ('cha', 'CharismaUp', 'CHA'), ('spd', 'SpeedUp', 'SPD'),
         ('lck', 'LuckUp', 'LCK')]
# Filter effects: localization key, English fallback, game identifiers that
# grant or inflict it. Identifiers are matched exactly against gon keys/values.
EFFECTS = [
    ('BLEED', 'Bleed', ['Bleed', 'BleedThorns']),
    ('POISON', 'Poison', ['Poison', 'PoisonThorns', 'Poisonous', 'PoisonLace']),
    ('BURN', 'Burn', ['Burn']),
    ('FREEZE', 'Freeze', ['Freeze', 'Frozen']),
    ('STUN', 'Stun', ['Stun']),
    ('BRUISE', 'Bruise', ['Bruise']),
    ('CONFUSION', 'Confusion', ['Confusion']),
    ('SLOW', 'Slow', ['Slow']),
    ('FEAR', 'Fear', ['Fear']),
    ('WEAKNESS', 'Weakness', ['Weakness']),
    ('THORNS', 'Thorns', ['Thorns', 'BleedThorns', 'PoisonThorns']),
    ('BRACE', 'Brace', ['Brace']),
    ('SHIELD', 'Shield', ['Shield']),
    ('DIVINESHIELD', 'Holy Shield', ['DivineShield']),
    ('HEALTHREGEN', 'Health Regen', ['HealthRegenUp', 'HealthRegen']),
    ('DODGECHANCE', 'Dodge Chance', ['DodgeChance', 'ArmorDodgeChance']),
    ('CHARGE', 'Charge', ['Charge']),
]


def strip_comments(text):
    return re.sub(r'//[^\n]*', '', text)


def top_level_blocks(text):
    blocks, depth, name, start, previous = {}, 0, None, 0, None
    for token in re.finditer(r'\{|\}|[^\s{}]+', text):
        value = token.group()
        if value == '{':
            if depth == 0:
                name, start = previous, token.end()
            depth += 1
        elif value == '}':
            depth -= 1
            if depth == 0 and name:
                blocks[name] = text[start:token.start()]
                name = None
        previous = value
    return blocks


def identifier_bits():
    bits = {}
    for index, (_, _, identifiers) in enumerate(EFFECTS):
        for identifier in identifiers:
            bits[identifier] = bits.get(identifier, 0) | (1 << index)
    return bits


def ability_bits(game):
    archive = Gpak(game / 'resources.gpak')
    lookup, abilities = identifier_bits(), {}
    for name in ABILITY_FILES:
        text = strip_comments(archive.read(name).decode('utf-8', errors='replace'))
        for ability, body in top_level_blocks(text).items():
            mask = 0
            for word in set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', body)):
                mask |= lookup.get(word, 0)
            if mask and re.fullmatch(r'[A-Za-z0-9_]{1,63}', ability):
                abilities[ability] = abilities.get(ability, 0) | mask
    return dict(sorted(abilities.items()))


def render(abilities):
    lines = ['/* Generated by tools/generate_item_traits.py from the supported build\'s',
             ' * ability data. Do not edit; regenerate after changing the tables there. */',
             '#pragma once',
             '#include <stdint.h>',
             f'#define IQ_STAT_COUNT {len(STATS)}',
             f'#define IQ_EFFECT_COUNT {len(EFFECTS)}',
             'static const char* const iq_stat_fields[IQ_STAT_COUNT]={' + ','.join(f'"{s[0]}"' for s in STATS) + '};',
             'static const char* const iq_stat_up_passives[IQ_STAT_COUNT]={' + ','.join(f'"{s[1]}"' for s in STATS) + '};',
             'static const char* const iq_stat_keys[IQ_STAT_COUNT][2]={' +
             ','.join(f'{{"KEYWORD_{s[2]}UP_NAME","KEYWORD_{s[2]}DOWN_NAME"}}' for s in STATS) + '};',
             'static const wchar_t* const iq_stat_fallbacks[IQ_STAT_COUNT]={' + ','.join(f'L"{s[2].title()}"' for s in STATS) + '};',
             'static const char* const iq_effect_keys[IQ_EFFECT_COUNT]={' + ','.join(f'"KEYWORD_{e[0]}_NAME"' for e in EFFECTS) + '};',
             'static const wchar_t* const iq_effect_fallbacks[IQ_EFFECT_COUNT]={' + ','.join(f'L"{e[1]}"' for e in EFFECTS) + '};',
             'typedef struct { const char* name; uint32_t bits; } IQTraitName;',
             '/* Sorted by name for binary search. */',
             'static const IQTraitName iq_effect_identifiers[]={']
    lines += [f'    {{"{name}",0x{bits:x}u}},' for name, bits in sorted(identifier_bits().items())]
    lines += ['};', 'static const IQTraitName iq_ability_effects[]={']
    lines += [f'    {{"{name}",0x{bits:x}u}},' for name, bits in abilities.items()]
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--game', required=True, type=Path)
    cli.add_argument('--check', action='store_true', help='Fail if the committed header is out of date')
    args = cli.parse_args()
    abilities = ability_bits(args.game)
    text = render(abilities)
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != text:
            sys.exit('inventory_trait_tables.h is out of date; run tools/generate_item_traits.py')
        print(f'Trait tables current: {len(abilities)} abilities with filter effects.')
        return
    OUTPUT.write_bytes(text.encode('utf-8'))
    print(f'Wrote {OUTPUT.relative_to(ROOT)}: {len(abilities)} abilities with filter effects.')


if __name__ == '__main__':
    main()
